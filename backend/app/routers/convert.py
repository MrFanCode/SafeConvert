"""Conversion endpoints.

Design rules that apply to every route here:

* **Nothing is written to disk.** The whole request is held in memory, so a
  crash cannot leave a converted copy of someone's document behind.
* **Output is always PNG / JPEG / PDF.** Never SVG, never HTML. This is the
  control that prevents converter-XSS (see app.validation for the threat
  model).
* **Every upload is validated before a parser sees it**, and the declared
  content type is checked against the actual magic bytes.
* **Errors are typed** so the envelope in app.errors can produce a vague,
  safe message instead of a traceback.
* Work runs in a threadpool with a hard timeout, so one pathological file
  cannot block the event loop.
"""

from __future__ import annotations

import asyncio
import io
import logging
import re
import zipfile

from fastapi import APIRouter, File, Query, Request, UploadFile
from fastapi.responses import Response

from ..config import Settings, get_settings
from ..converters.docx import docx_to_pdf
from ..converters.images import images_to_pdf
from ..converters.pdf import pdf_to_images
from ..converters.svg import svg_to_image
from ..errors import (
    ConversionError,
    FileTooLargeError,
    MaliciousFileError,
    UnsupportedTypeError,
)
from ..validation import validate_upload

logger = logging.getLogger("safeconvert.routes")

router = APIRouter()

# Fixed Content-Disposition filename. The client's filename is attacker
# controlled; RFC 6266 quoting plus a strict whitelist in
# validation.sanitise_filename means it cannot inject headers, but a
# generated name removes the question entirely.
_SAFE_TOKEN = re.compile(r"[^A-Za-z0-9._-]+")

_PDF_STEM = "converted"


def _attachment_name(stem: str, extension: str) -> str:
    token = _SAFE_TOKEN.sub("_", stem)[:60].strip("._-") or _PDF_STEM
    return f"{token}.{extension}"


def _download(data: bytes, filename: str, media_type: str) -> Response:
    """A binary download with a hardened content type.

    ``X-Content-Type-Options: nosniff`` matters here: without it a browser
    may ignore the declared type and guess, which is how a mislabelled
    response becomes script execution.
    """
    return Response(
        content=data,
        media_type=media_type,
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
            "X-Content-Type-Options": "nosniff",
            "Content-Security-Policy": "default-src 'none'; sandbox",
            "Cache-Control": "no-store",
        },
    )


def _zip_download(entries: list[tuple[str, bytes]], stem: str) -> Response:
    """Bundle multiple outputs into a ZIP.

    The archive is built in memory. Entry names are generated by us, never
    taken from the upload.
    """
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, payload in entries:
            zf.writestr(name, payload)
    return _download(buffer.getvalue(), _attachment_name(stem, "zip"), "application/zip")


async def _read_upload(file: UploadFile, settings: Settings) -> bytes:
    """Read an upload, enforcing the size ceiling *while streaming*.

    Reading the whole body first and then checking its length is the mistake
    this avoids: by the time you know it is too large, you have already
    allocated it.

    Note on Starlette's own limit: ``MultiPartParser.max_part_size`` defaults
    to 1 MiB and silently truncates a larger file part. Without raising it,
    a 6 MB upload arrives here already cut to 1 MB, so the request is not
    rejected as too large — it is fed to a PDF parser as a truncated file and
    reported as "corrupt", which is both the wrong status code and a
    misleading message. ``max_upload_bytes`` is raised to match in
    ``create_app``; this function remains the authoritative check.
    """
    chunks: list[bytes] = []
    total = 0
    while True:
        chunk = await file.read(64 * 1024)
        if not chunk:
            break
        total += len(chunk)
        if total > settings.max_upload_bytes:
            raise FileTooLargeError()
        chunks.append(chunk)
    return b"".join(chunks)


async def _run_with_timeout(func, *args, settings: Settings | None = None, **kwargs):
    """Run CPU-bound conversion work off the event loop, with a ceiling.

    Conversions are synchronous C/Rust/Python work. Called directly on the
    event loop they would block every other request for the duration, so they
    go to a worker thread. The timeout cannot actually interrupt a thread
    already running C code, which is why the resource ceilings inside the
    converters are the real control; this bounds the common case.
    """
    s = settings or get_settings()
    loop = asyncio.get_running_loop()
    return await asyncio.wait_for(
        loop.run_in_executor(None, lambda: func(*args, **kwargs)),
        timeout=s.conversion_timeout_seconds,
    )


def _pdf_job(data: bytes, dpi: int, fmt: str, settings: Settings) -> list[bytes]:
    return pdf_to_images(data, dpi=dpi, image_format=fmt, settings=settings)


def file_stem(filename: str) -> str:
    """Stem of a sanitised filename, without its extension."""
    return filename.rsplit(".", 1)[0] if "." in filename else filename


# ------------------------------------------------------------------ health
@router.get("/health", summary="Liveness and readiness probe")
async def health() -> dict[str, object]:
    """Used by Docker HEALTHCHECK and Vercel. Deliberately does no work.

    It must not touch a converter: a healthcheck that runs a conversion will
    eventually fail on a weird input and take a healthy container out of
    rotation.
    """
    settings = get_settings()
    return {
        "status": "ok",
        "service": settings.app_name,
        "version": settings.version,
        "docs_enabled": settings.enable_docs,
    }


# ----------------------------------------------------------------- pdf -> png
@router.post(
    "/pdf-to-image",
    summary="Convert a PDF to PNG or JPEG images",
    response_class=Response,
    responses={
        200: {
            "content": {
                "image/png": {},
                "image/jpeg": {},
                "application/zip": {
                    "description": "Returned when the PDF has more than one page."
                },
            }
        },
        413: {"description": "File exceeds the upload limit."},
        415: {"description": "Not a PDF."},
        422: {"description": "Rejected by a safety check, or unreadable."},
    },
)
async def pdf_to_image(
    request: Request,
    file: UploadFile = File(..., description="A PDF file."),
    format: str = Query("png", pattern="^(png|jpeg|jpg)$"),
    dpi: int = Query(150, ge=36, le=400),
    page: int | None = Query(None, ge=1, description="Render a single page instead of all."),
) -> Response:
    settings = get_settings()
    data = await _read_upload(file, settings)

    info = validate_upload(data, file.filename or "", settings)
    if info.kind != "pdf":
        raise UnsupportedTypeError("This endpoint accepts PDF files only.")

    images = await _run_with_timeout(_pdf_job, data, dpi, format, settings)

    if page is not None:
        if page > len(images):
            raise ConversionError(
                f"This PDF has {len(images)} pages; page {page} does not exist.",
                code="page_out_of_range",
            )
        images = [images[page - 1]]

    stem = file_stem(info.filename)
    if len(images) == 1:
        ext = "png" if format == "png" else "jpg"
        media = "image/png" if format == "png" else "image/jpeg"
        return _download(images[0], _attachment_name(stem, ext), media)

    ext = "png" if format == "png" else "jpg"
    entries = [
        (f"{stem}-page-{i + 1:04d}.{ext}", payload) for i, payload in enumerate(images)
    ]
    return _zip_download(entries, stem)


# -------------------------------------------------------------- images -> pdf
@router.post(
    "/images-to-pdf",
    summary="Convert one or more images to a PDF",
    response_class=Response,
    responses={200: {"content": {"application/pdf": {}}}},
)
async def images_to_pdf_endpoint(
    request: Request,
    files: list[UploadFile] = File(..., description="One or more images, in page order."),
    compress: bool = Query(True, description="Re-compress to JPEG for a smaller file."),
) -> Response:
    settings = get_settings()
    if not files:
        raise ConversionError("Upload at least one image.", code="no_input")
    if len(files) > settings.max_pdf_pages:
        raise MaliciousFileError(f"At most {settings.max_pdf_pages} images are allowed.")

    payloads: list[bytes] = []
    stem = "converted"
    for index, upload in enumerate(files):
        data = await _read_upload(upload, settings)
        info = validate_upload(data, upload.filename or "", settings)
        if info.kind == "pdf":
            raise UnsupportedTypeError(
                f"File {index + 1} is a PDF. Convert it with /pdf-to-image instead."
            )
        if info.kind != "image":
            raise UnsupportedTypeError(
                f"File {index + 1} is not an image (it looks like {info.kind})."
            )
        payloads.append(data)
        if index == 0:
            stem = file_stem(info.filename)

    pdf_bytes = await _run_with_timeout(
        images_to_pdf, payloads, compress=compress, settings=settings
    )
    return _download(pdf_bytes, _attachment_name(stem, "pdf"), "application/pdf")


# ---------------------------------------------------------------- svg -> png
@router.post(
    "/svg-to-image",
    summary="Convert an SVG to PNG or JPEG",
    response_class=Response,
    responses={
        200: {"content": {"image/png": {}, "image/jpeg": {}}},
        422: {"description": "Rejected by a safety check, or unparseable."},
    },
)
async def svg_to_image_endpoint(
    request: Request,
    file: UploadFile = File(..., description="An SVG file."),
    format: str = Query("png", pattern="^(png|jpeg|jpg)$"),
    width: int | None = Query(None, ge=1, le=20000),
    height: int | None = Query(None, ge=1, le=20000),
    dpi: int | None = Query(None, ge=36, le=600),
) -> Response:
    settings = get_settings()
    data = await _read_upload(file, settings)

    info = validate_upload(data, file.filename or "", settings)
    if info.kind != "svg":
        raise UnsupportedTypeError("This endpoint accepts SVG files only.")

    png_bytes = await _run_with_timeout(
        svg_to_image,
        data,
        output_format=format,
        width=width,
        height=height,
        dpi=dpi,
        settings=settings,
    )

    ext = "png" if format == "png" else "jpg"
    media = "image/png" if format == "png" else "image/jpeg"
    stem = file_stem(info.filename)
    return _download(png_bytes, _attachment_name(stem, ext), media)


# --------------------------------------------------------------- docx -> pdf
@router.post(
    "/docx-to-pdf",
    summary="Convert a DOCX to PDF",
    response_class=Response,
    responses={200: {"content": {"application/pdf": {}}}},
)
async def docx_to_pdf_endpoint(
    request: Request,
    file: UploadFile = File(..., description="A .docx file (Word Open XML)."),
) -> Response:
    settings = get_settings()
    data = await _read_upload(file, settings)

    info = validate_upload(data, file.filename or "", settings)
    if info.kind != "docx":
        raise UnsupportedTypeError(
            "This endpoint accepts .docx files. Legacy .doc is not supported."
        )

    pdf_bytes, stats = await _run_with_timeout(docx_to_pdf, data, settings)

    logger.info(
        "docx converted: chars=%s paragraphs=%s tables=%s lists=%s headings=%s",
        stats.get("source_characters"),
        stats.get("paragraphs"),
        stats.get("tables"),
        stats.get("lists"),
        stats.get("headings"),
    )
    stem = file_stem(info.filename)
    return _download(pdf_bytes, _attachment_name(stem, "pdf"), "application/pdf")
